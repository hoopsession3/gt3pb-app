const n = (s) => (s ? Number(s) : 0);
/** The definers callable at a ledger, and which of them signed out. */
export function definersAt(ledger) {
  const L = Number(ledger);
  const live = DEFINERS.filter((d) => n(d.since) <= L && (!d.until || n(d.until) > L));
  const anon = live.filter((d) => d.roles.includes("anon") && (!d.anonUntil || n(d.anonUntil) > L));
  return { all: live.map((d) => d.fn).sort(), anon: anon.map((d) => d.fn).sort() };
}
